const manifestPath = "go_test/MANIFEST.json"

// This main() gets all the WPT test renaming and deletions between two WPT SHAs, then it deletes/renames
// appropriately in the wpt-metadata repository. This program will roll in the latest WPT SHA once a day
// through a cron job.
func main() {
	// Read the current manifest before it is overwritten so that renames can be
	// detected by diffing the old and new manifests.
	oldManifest, err := ioutil.ReadFile(manifestPath)
	if err != nil {
		log.Printf("Unable to read %s; manifest-based rename detection is disabled: %s", manifestPath, err)
	}

	shaAfter := updateManifest()
	if shaAfter == "" {
		log.Fatal("Unable to update manifest and get shaAfter")
	}

	data, err := ioutil.ReadFile("go_test/WPT_SHA.json")
	if err != nil {
		log.Fatalf("Unable to read go_test/WPT_SHA.json: %s", err)
	}

	err = ioutil.WriteFile("go_test/WPT_SHA.json", []byte(shaAfter), 0644)
	if err != nil {
		log.Fatalf("Unable to update go_test/WPT_SHA.json with shaAfter: %s", err)
	}
	shaBefore := string(data)
	if shaBefore == shaAfter {
		fmt.Println("Nothing to do since the before/after SHAs are the same:", shaBefore)
		return
	}

	// Plumb the SHA information from a text file, WPT SHA rolls on a daily basis
	renames, deletes := getChangesBetweenSHAs(context.Background(), shaBefore, shaAfter)
	if renames == nil {
		renames = make(map[string]string)
	}

	// The GitHub compare API returns at most 300 changed files, so large WPT
	// rolls silently miss renames and deletions. Supplement it with changes
	// detected by diffing the old and new manifests.
	if newManifest, err := ioutil.ReadFile(manifestPath); err == nil && oldManifest != nil {
		diff, err := diffManifests(oldManifest, newManifest)
		if err != nil {
			fmt.Println("Failed to diff manifests:", err)
		} else {
			added := mergeRenames(renames, diff.Renames)
			fmt.Println("Found", added, "additional renames by diffing manifests")
			deletes = mergeDeletes(deletes, diff.Deletes)
			fmt.Println("Found", len(diff.Deletes), "deleted test IDs by diffing manifests")
			for _, r := range diff.PossibleRenames {
				fmt.Println("Not deleting possibly renamed test (needs a human):", r)
			}
		}
	}
	deletes = filterDeletes(deletes, renames)

	fmt.Println("Renaming WPT tests...")
	for before, after := range renames {
		renameMetadata(before, after)
	}

	fmt.Println("Deleting WPT tests...")
	for _, delete := range deletes {
		go_util.DeleteTestFromMetadata(delete)
	}
}

// renameMetadata deletes the before WPT test and adds the after WPT test, if exists.
func renameMetadata(before, after string) {
	metadataLinks := go_util.DeleteTestFromMetadata(before)
	if len(metadataLinks) == 0 {
		return
	}

	_, afterTestname := go_util.SplitTestPath(after)
	// Rename the before test name to the after test name.
	for linkIndex, link := range metadataLinks {
		for resultIndex := range link.Results {
			fmt.Println("Renaming", before, after)
			metadataLinks[linkIndex].Results[resultIndex].TestPath = afterTestname
		}
	}

	for _, link := range metadataLinks {
		go_util.WriteMetadataLink(after, link)
	}
}

// getChangesBetweenSHAs returns all the renamed and deleted files between two WPT SHAs.
// TODO(kyleju): In WPT tests, if we have a foo.any.js file, that would have tests
// foo.any.html, foo.any.worker.html and foo.any.sharedworker.html. To perfectly rename/map all tests,
// we need MANIFEST information.
func getChangesBetweenSHAs(ctx context.Context, shaBefore, shaAfter string) (map[string]string, []string) {
	fmt.Println("Getting WPT changes bewtween", shaBefore, "and", shaAfter)
	if shaBefore == shaAfter {
		fmt.Println("Nothing to do since the before/after SHAs are the same:", shaBefore)
		return nil, nil
	}
	githubClient := github.NewClient(nil)
	comparison, _, err := githubClient.Repositories.CompareCommits(ctx, "web-platform-tests", "wpt", shaBefore, shaAfter)
	if err != nil || comparison == nil {
		fmt.Println("Failed to fetch diff for", shaBefore[:7], shaAfter[:7], ":", err.Error())
		return nil, nil
	}

	renames := make(map[string]string)
	deletes := make([]string, 0)
	for _, file := range comparison.Files {
		if file.GetStatus() == "renamed" {
			is, was := file.GetFilename(), file.GetPreviousFilename()
			renames[was] = is
		}

		if file.GetStatus() == "removed" {
			deletes = append(deletes, file.GetFilename())
		}
	}
	return renames, deletes
}

// manifestFile is a test file listed in a WPT MANIFEST.json.
type manifestFile struct {
	// Hash is the content hash of the file.
	Hash string
	// TestIDs are the test URLs (without the leading slash) generated by the
	// file, e.g. foo.any.html and foo.any.worker.html for foo.any.js, or
	// foo.html?a and foo.html?b for a file with variants.
	TestIDs []string
}

// manifestFiles returns every test file listed in a WPT MANIFEST.json, keyed
// by file path. Support files are skipped.
func manifestFiles(data []byte) (map[string]manifestFile, error) {
	var manifest struct {
		Items map[string]json.RawMessage `json:"items"`
	}
	if err := json.Unmarshal(data, &manifest); err != nil {
		return nil, err
	}

	files := make(map[string]manifestFile)
	for testType, trie := range manifest.Items {
		if testType == "support" {
			// Support files (resources, reftest references) are not tests and
			// have no metadata.
			continue
		}
		if err := walkManifestTrie(trie, "", files); err != nil {
			return nil, fmt.Errorf("invalid %s manifest items: %w", testType, err)
		}
	}
	return files, nil
}

// walkManifestTrie walks a manifest path trie. Directories are JSON objects;
// files are JSON arrays of the form [hash, [url-or-null, ...extras], ...].
func walkManifestTrie(raw json.RawMessage, prefix string, files map[string]manifestFile) error {
	var dir map[string]json.RawMessage
	if err := json.Unmarshal(raw, &dir); err == nil {
		for name, child := range dir {
			if err := walkManifestTrie(child, path.Join(prefix, name), files); err != nil {
				return err
			}
		}
		return nil
	}

	var entry []json.RawMessage
	if err := json.Unmarshal(raw, &entry); err != nil || len(entry) == 0 {
		return fmt.Errorf("unexpected manifest entry for %q", prefix)
	}
	file := files[prefix]
	// A null hash is left empty and ignored by rename detection.
	_ = json.Unmarshal(entry[0], &file.Hash)
	for _, rawTest := range entry[1:] {
		var test []json.RawMessage
		if err := json.Unmarshal(rawTest, &test); err != nil || len(test) == 0 {
			continue
		}
		var url *string
		_ = json.Unmarshal(test[0], &url)
		if url == nil || *url == "" {
			// A null URL means the test URL is the file path itself.
			file.TestIDs = append(file.TestIDs, prefix)
		} else {
			file.TestIDs = append(file.TestIDs, strings.TrimPrefix(*url, "/"))
		}
	}
	files[prefix] = file
	return nil
}

// maxManifestDeleteFraction caps manifest-based deletions. If more than this
// fraction of the old manifest's files disappear, the new manifest is assumed
// to be incomplete and no metadata is deleted. Real WPT rolls remove well
// under 1% of files.
var maxManifestDeleteFraction = 0.02

// manifestDiff is the set of metadata changes implied by two manifests.
type manifestDiff struct {
	// Renames maps old test file paths to new test file paths.
	Renames map[string]string
	// Deletes lists test IDs (and file paths) of test files that were removed
	// without a successor.
	Deletes []string
	// PossibleRenames lists removed files ("old -> candidate") that were not
	// deleted because a similarly named file was added. These need a human.
	PossibleRenames []string
}

// diffManifests compares two WPT manifests.
//
// A test file that disappears is treated as renamed when exactly one newly
// added file has the same content hash. A file that disappears and whose
// content hash matches no added file is treated as deleted, and all of its
// test IDs are returned for deletion. Files whose hash matches several added
// files are left alone.
func diffManifests(oldData, newData []byte) (manifestDiff, error) {
	diff := manifestDiff{Renames: make(map[string]string)}
	oldFiles, err := manifestFiles(oldData)
	if err != nil {
		return diff, fmt.Errorf("failed to parse old manifest: %w", err)
	}
	newFiles, err := manifestFiles(newData)
	if err != nil {
		return diff, fmt.Errorf("failed to parse new manifest: %w", err)
	}

	removedByHash := make(map[string][]string)
	var removedNoHash []string
	for p, f := range oldFiles {
		if _, ok := newFiles[p]; ok {
			continue
		}
		if f.Hash == "" {
			removedNoHash = append(removedNoHash, p)
		} else {
			removedByHash[f.Hash] = append(removedByHash[f.Hash], p)
		}
	}
	addedByHash := make(map[string][]string)
	for p, f := range newFiles {
		if _, ok := oldFiles[p]; !ok && f.Hash != "" {
			addedByHash[f.Hash] = append(addedByHash[f.Hash], p)
		}
	}

	var deletedFiles []string
	for hash, removed := range removedByHash {
		added := addedByHash[hash]
		switch {
		case len(added) == 0:
			deletedFiles = append(deletedFiles, removed...)
		case len(removed) == 1 && len(added) == 1:
			diff.Renames[removed[0]] = added[0]
		}
		// Otherwise ambiguous (e.g. identical files): leave for a human.
	}
	deletedFiles = append(deletedFiles, removedNoHash...)

	// A removed file may have been renamed and edited in the same roll, in
	// which case its hash no longer matches. Deleting its metadata would
	// silently drop triage (bug links, labels) that a human would move to the
	// new name, so leave such files for a human instead.
	renameTargets := make(map[string]bool)
	for _, after := range diff.Renames {
		renameTargets[after] = true
	}
	var unmatchedAdded []string
	for p := range newFiles {
		if _, ok := oldFiles[p]; !ok && !renameTargets[p] {
			unmatchedAdded = append(unmatchedAdded, p)
		}
	}
	candidates := newRenameCandidates(unmatchedAdded)
	kept := deletedFiles[:0]
	for _, p := range deletedFiles {
		if c := candidates.find(p); c != "" {
			diff.PossibleRenames = append(diff.PossibleRenames, p+" -> "+c)
		} else {
			kept = append(kept, p)
		}
	}
	deletedFiles = kept
	sort.Strings(diff.PossibleRenames)

	// Metadata refers to test IDs, which can differ from file paths (variants
	// such as foo.html?a, or foo.any.html generated from foo.any.js). Map the
	// test IDs of each renamed file onto the renamed file's test IDs.
	fileRenames := make([]string, 0, len(diff.Renames))
	for before := range diff.Renames {
		fileRenames = append(fileRenames, before)
	}
	for _, before := range fileRenames {
		after := diff.Renames[before]
		for oldID, newID := range mapTestIDs(before, after, oldFiles[before].TestIDs, newFiles[after].TestIDs) {
			if _, ok := diff.Renames[oldID]; !ok {
				diff.Renames[oldID] = newID
			}
		}
	}

	if len(oldFiles) > 0 && float64(len(deletedFiles)) > maxManifestDeleteFraction*float64(len(oldFiles)) {
		fmt.Printf("Skipping manifest-based deletions: %d of %d test files removed, which exceeds the %.0f%% safety limit\n",
			len(deletedFiles), len(oldFiles), maxManifestDeleteFraction*100)
		return diff, nil
	}

	// Never delete a test ID that still exists in the new manifest, e.g. when
	// foo.any.js is replaced by a foo.any.html file.
	stillExists := make(map[string]bool)
	for p, f := range newFiles {
		stillExists[p] = true
		for _, id := range f.TestIDs {
			stillExists[id] = true
		}
	}

	sort.Strings(deletedFiles)
	seen := make(map[string]bool)
	for _, p := range deletedFiles {
		for _, id := range append([]string{p}, oldFiles[p].TestIDs...) {
			if !seen[id] && !stillExists[id] {
				seen[id] = true
				diff.Deletes = append(diff.Deletes, id)
			}
		}
	}
	return diff, nil
}

// testNameFlags are trailing name components that do not identify a test,
// e.g. foo.tentative.any.js and foo.window.js both normalize to foo.
var testNameFlags = map[string]bool{
	"html": true, "htm": true, "xht": true, "xhtml": true, "svg": true, "js": true,
	"tentative": true, "any": true, "window": true, "worker": true,
	"sharedworker": true, "serviceworker": true, "https": true, "h2": true,
	"sub": true, "optional": true, "manual": true, "www": true,
}

// normalizeTestName returns a file's base name without its extension and
// trailing WPT flags.
func normalizeTestName(p string) string {
	parts := strings.Split(path.Base(p), ".")
	for len(parts) > 1 && testNameFlags[parts[len(parts)-1]] {
		parts = parts[:len(parts)-1]
	}
	return strings.Join(parts, ".")
}

// renameCandidates indexes added files to find likely successors of removed
// files whose content changed.
type renameCandidates struct {
	byName map[string]string
	byDir  map[string][]string
}

func newRenameCandidates(added []string) renameCandidates {
	sort.Strings(added)
	c := renameCandidates{byName: make(map[string]string), byDir: make(map[string][]string)}
	for _, p := range added {
		name := normalizeTestName(p)
		if _, ok := c.byName[name]; !ok {
			c.byName[name] = p
		}
		c.byDir[path.Dir(p)] = append(c.byDir[path.Dir(p)], p)
	}
	return c
}

// minRenameSimilarity is the minimum name similarity for an added file in the
// same directory to be considered a possible rename of a removed file.
const minRenameSimilarity = 0.75

// find returns an added file that is likely the removed file renamed: one
// with the same normalized name anywhere, or a similar name in the same
// directory. It returns "" if there is none.
func (c renameCandidates) find(removed string) string {
	name := normalizeTestName(removed)
	if p, ok := c.byName[name]; ok {
		return p
	}
	for _, p := range c.byDir[path.Dir(removed)] {
		if nameSimilarity(name, normalizeTestName(p)) >= minRenameSimilarity {
			return p
		}
	}
	return ""
}

// nameSimilarity returns 1 - levenshtein(a, b) / max(len(a), len(b)).
func nameSimilarity(a, b string) float64 {
	if a == b {
		return 1
	}
	ra, rb := []rune(a), []rune(b)
	prev := make([]int, len(rb)+1)
	cur := make([]int, len(rb)+1)
	for j := range prev {
		prev[j] = j
	}
	for i := 1; i <= len(ra); i++ {
		cur[0] = i
		for j := 1; j <= len(rb); j++ {
			cost := 1
			if ra[i-1] == rb[j-1] {
				cost = 0
			}
			cur[j] = min(prev[j]+1, cur[j-1]+1, prev[j-1]+cost)
		}
		prev, cur = cur, prev
	}
	longest := len(ra)
	if len(rb) > longest {
		longest = len(rb)
	}
	return 1 - float64(prev[len(rb)])/float64(longest)
}

// mapTestIDs maps the test IDs of a renamed file to the test IDs of its new
// name, by replacing the file's path (minus its extension) at the start of
// each test ID. Test IDs without a counterpart in newIDs are skipped.
func mapTestIDs(before, after string, oldIDs, newIDs []string) map[string]string {
	oldStem := strings.TrimSuffix(before, path.Ext(before))
	newStem := strings.TrimSuffix(after, path.Ext(after))
	exists := make(map[string]bool)
	for _, id := range newIDs {
		exists[id] = true
	}
	mapped := make(map[string]string)
	for _, id := range oldIDs {
		if !strings.HasPrefix(id, oldStem) {
			continue
		}
		newID := newStem + strings.TrimPrefix(id, oldStem)
		if id != newID && exists[newID] {
			mapped[id] = newID
		}
	}
	return mapped
}

// mergeDeletes appends deletes from extra that are not already present.
func mergeDeletes(deletes, extra []string) []string {
	seen := make(map[string]bool)
	for _, d := range deletes {
		seen[d] = true
	}
	for _, d := range extra {
		if !seen[d] {
			seen[d] = true
			deletes = append(deletes, d)
		}
	}
	return deletes
}

// mergeRenames adds renames from extra that are not already in renames, and
// returns the number added.
func mergeRenames(renames, extra map[string]string) int {
	added := 0
	for before, after := range extra {
		if _, ok := renames[before]; !ok {
			renames[before] = after
			added++
		}
	}
	return added
}

// filterDeletes removes paths that are handled as renames.
func filterDeletes(deletes []string, renames map[string]string) []string {
	filtered := make([]string, 0, len(deletes))
	for _, d := range deletes {
		if _, ok := renames[d]; !ok {
			filtered = append(filtered, d)
		}
	}
	return filtered
}

// updateManifest updates go_test/MANIFEST.json and returns the latest WPT SHA.
func updateManifest() string {
	resp, err := http.Get("https://wpt.fyi/api/manifest?sha=latest")
	if err != nil {
		return ""
	}
	defer resp.Body.Close()
	data, err := ioutil.ReadAll(resp.Body)
	if err != nil {
		return ""
	}
	err = ioutil.WriteFile(manifestPath, data, 0644)
	if err != nil {
		return ""
	}
	sha := resp.Header.Get("x-wpt-sha")
	return sha
}
